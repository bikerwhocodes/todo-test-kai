// Generates .env.local with locally-random passwords.
//
// Never overwrites credentials or secrets that are already there — a
// regenerated password would no longer match the one baked into the Postgres
// volume. Explicit port/project overrides only update those settings and the
// derived URLs. Missing variables are still appended for older checkouts.
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const TARGET = ".env.local";
const pw = () => randomBytes(24).toString("base64url");

const existing = existsSync(TARGET) ? readFileSync(TARGET, "utf8") : "";
const current = new Map(
  existing
    .split("\n")
    .filter((l) => l.trim() && !l.trimStart().startsWith("#"))
    .map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1)]),
);
const port = process.env.NEXTUP_DB_PORT || current.get("NEXTUP_DB_PORT") || "55433";
const composeProject = process.env.COMPOSE_PROJECT_NAME || current.get("COMPOSE_PROJECT_NAME");
const host = `127.0.0.1:${port}`;

// Reuse any password already present; only generate what is absent.
const secret = (name, make) => current.get(name) || make();
const superPw = secret("POSTGRES_PASSWORD", pw);
const ownerPw = secret("NEXTUP_OWNER_PASSWORD", pw);
const runtimePw = secret("NEXTUP_RUNTIME_PASSWORD", pw);
const authPw = secret("NEXTUP_AUTH_PASSWORD", pw);

const wanted = {
  NEXTUP_DB_PORT: port,
  ...(composeProject ? { COMPOSE_PROJECT_NAME: composeProject } : {}),
  POSTGRES_PASSWORD: superPw,
  NEXTUP_OWNER_PASSWORD: ownerPw,
  NEXTUP_RUNTIME_PASSWORD: runtimePw,
  NEXTUP_AUTH_PASSWORD: authPw,
  POSTGRES_SUPERUSER_URL: `postgresql://postgres:${superPw}@${host}/nextup`,
  MIGRATION_DATABASE_URL: `postgresql://nextup_owner:${ownerPw}@${host}/nextup`,
  DATABASE_URL: `postgresql://nextup_runtime:${runtimePw}@${host}/nextup`,
  AUTH_DATABASE_URL: `postgresql://nextup_auth:${authPw}@${host}/nextup`,
  BETTER_AUTH_SECRET: secret("BETTER_AUTH_SECRET", () => pw() + pw()),
  BETTER_AUTH_URL: "http://127.0.0.1:3100",
};

const derivedUrls = [
  "POSTGRES_SUPERUSER_URL",
  "MIGRATION_DATABASE_URL",
  "DATABASE_URL",
  "AUTH_DATABASE_URL",
];
const overridden = new Set([
  ...(process.env.NEXTUP_DB_PORT ? ["NEXTUP_DB_PORT", ...derivedUrls] : []),
  ...(process.env.COMPOSE_PROJECT_NAME ? ["COMPOSE_PROJECT_NAME"] : []),
]);
const changed = Object.keys(wanted).filter(
  (key) => !current.has(key) || (overridden.has(key) && current.get(key) !== wanted[key]),
);

if (existing && changed.length === 0) {
  console.log(`${TARGET} is already complete — leaving it untouched.`);
  process.exit(0);
}

if (!existing) {
  const body = Object.entries(wanted).map(([k, v]) => `${k}=${v}`).join("\n");
  writeFileSync(
    TARGET,
    `# Generated by \`npm run env:init\`. Local development only. Git-ignored.\n${body}\n`,
    { mode: 0o600 },
  );
  console.log(`Wrote ${TARGET} with locally-generated passwords.`);
} else {
  const replaced = changed.filter((key) => current.has(key));
  const added = changed.filter((key) => !current.has(key));
  let next = existing;
  for (const key of replaced) {
    next = next.replace(new RegExp(`^${key}=.*$`, "m"), `${key}=${wanted[key]}`);
  }
  if (added.length > 0) {
    const body = added.map((key) => `${key}=${wanted[key]}`).join("\n");
    next = `${next.endsWith("\n") ? next : next + "\n"}# Added by \`npm run env:init\`.\n${body}\n`;
  }
  writeFileSync(TARGET, next, { mode: 0o600 });
  console.log(`Updated ${changed.length} variable(s) in ${TARGET}: ${changed.join(", ")}`);
}
